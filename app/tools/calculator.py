

class Calculator():

    def __init__(self):
        pass

    @staticmethod
    def add(x: float, y: float) -> float:
        print("Adding", x, y)
        return x + y

    @staticmethod
    def subtract(x: float, y: float) -> float:
        print("Adding", x, y)
        return x - y

    @staticmethod
    def divide(x: float, y: float) -> float:
        print("Adding", x, y)
        return x / y

    @staticmethod
    def multiply(x: float, y: float) -> float:
        print("Adding", x, y)
        return x * y
